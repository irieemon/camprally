#!/usr/bin/env node
/**
 * Mirror the published Gumroad printables into this site.
 *
 *   node scripts/sync-printables.mjs
 *   node scripts/sync-printables.mjs --dry-run
 *
 * The printables are a second revenue rail living in its own repo
 * (~/camprally-printables) and sold on Gumroad. They earn roughly 100% margin
 * against Amazon's ~3%, so the traffic this site already has is worth pointing
 * at them — but only if the store's contents are actually visible here.
 *
 * Vercel builds from git and has no access to the sibling repo, so the product
 * list and cover art must be COMMITTED here rather than read at build time.
 * This script is the bridge: run it locally (run-cycle does, every cycle) and
 * it refreshes src/data/printables.json plus public/images/printables/.
 *
 * A missing sibling repo is not an error. It is the normal state on any machine
 * that is not Sean's, including CI — the script says so and leaves the
 * committed copy untouched, so a build never depends on a path outside git.
 *
 * The card art is each product's `art.jpg`, not its Gumroad cover or thumbnail.
 * Those have the title baked into them in a serif that predates this site's
 * type system, so at card size they render a second, clashing typography;
 * art.jpg is the bare watercolour and the page sets the title in its own font.
 */

import {
  readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync, statSync,
} from "node:fs";
import { homedir } from "node:os";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = process.env.PRINTABLES_REPO ?? `${homedir()}/camprally-printables`;
const OUT_JSON = `${ROOT}src/data/printables.json`;
const OUT_IMG = `${ROOT}public/images/printables`;
const STORE_URL = "https://camprally.gumroad.com";
const DRY = process.argv.includes("--dry-run");

const statePath = `${SRC}/state/products.json`;
if (!existsSync(statePath)) {
  console.log(`printables repo not found at ${SRC} — keeping the committed copy`);
  process.exit(0);
}

const state = JSON.parse(readFileSync(statePath, "utf8"));
const all = Array.isArray(state) ? state : Object.values(state.products ?? state);

/* Only what a buyer can actually reach. A product without a url has not been
 * published to Gumroad yet — the generator builds a backlog ahead of the
 * publisher, so "generated" is a normal, common, non-shippable state. */
const live = all
  .filter((p) => p.status === "published" && p.url)
  .sort((a, b) => String(b.publishedAt ?? "").localeCompare(String(a.publishedAt ?? "")));

const money = (cents) =>
  cents % 100 === 0 ? `$${cents / 100}` : `$${(cents / 100).toFixed(2)}`;

const products = [];
for (const p of live) {
  // The subtitle is the one piece of real marketing copy the generator writes;
  // falling back to the brief's angle keeps a card from rendering description-less.
  let subtitle = "";
  try {
    const spec = JSON.parse(readFileSync(`${SRC}/products/${p.slug}/spec.json`, "utf8"));
    subtitle = spec.spec?.subtitle ?? spec.brief?.angle ?? "";
  } catch { /* a product with no spec still lists, just without copy */ }

  const art = `${SRC}/products/${p.slug}/art.jpg`;
  let image = null;
  if (existsSync(art)) {
    image = `/images/printables/${p.slug}.jpg`;
    const dest = `${ROOT}public/images/printables/${p.slug}.jpg`;
    // Copy only on a real change, so an unchanged run leaves the working tree
    // clean and does not trigger a rebuild.
    const changed = !existsSync(dest) || statSync(dest).size !== statSync(art).size;
    if (changed && !DRY) {
      mkdirSync(OUT_IMG, { recursive: true });
      copyFileSync(art, dest);
      console.log(`  art: ${p.slug}.jpg`);
    }
  }

  products.push({
    slug: p.slug,
    title: p.title,
    subtitle,
    price: money(p.priceCents),
    priceCents: p.priceCents,
    pages: p.pages ?? null,
    url: p.url,
    image,
  });
}

/* No generatedAt stamp, deliberately. build-catalog.mjs used to write one on
 * every run, which made the file differ every run: a no-op sync then produced a
 * commit, a push and a full Vercel rebuild, and made "a product changed"
 * indistinguishable from "the script ran". */
const next = JSON.stringify({
  note: "Generated by scripts/sync-printables.mjs from the camprally-printables repo. Do not edit by hand.",
  storeUrl: STORE_URL,
  products,
}, null, 2) + "\n";

const prev = existsSync(OUT_JSON) ? readFileSync(OUT_JSON, "utf8") : "";
if (prev === next) {
  console.log(`printables: ${products.length} live · unchanged`);
  process.exit(0);
}
if (DRY) {
  console.log(`printables: ${products.length} live · would rewrite printables.json`);
  process.exit(0);
}
writeFileSync(OUT_JSON, next);
console.log(`printables: ${products.length} live · wrote src/data/printables.json`);
